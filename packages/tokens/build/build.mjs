/**
 * Token build.
 *
 * DTCG source (src/**) -> Style Dictionary -> output:
 *   dist/light.css                             :root { --background: ... }
 *   dist/dark.css                              .dark { --background: ... }
 *   dist/theme.css                             @theme inline { colour + radius }
 *                                              @theme static { motion, typography, spacing, shadow, breakpoint, container }
 *   dist/tokens.light.json / tokens.dark.json  resolved semantic tokens
 *   dist/tokens.foundation.json                all foundation ramps + JS module
 *   dist/dtcg/**                               one-way DTCG projection (Figma sync, codegen)
 *
 * Semantic token names are emitted verbatim as CSS custom properties, which is
 * what makes the output a drop-in replacement for a hand-written shadcn globals.css.
 */
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { rm, mkdir, readFile, writeFile, readdir } from 'node:fs/promises'
import StyleDictionary from 'style-dictionary'
import { expandTheme, themeSelector, THEME_SELECTOR_STYLE } from './themes.mjs'
import { readToken, cssVarName } from './serialize.mjs'
import { foundationTree, groupEntries } from './foundation.mjs'
import { writeDtcg } from './dtcg.mjs'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const PKG = path.join(HERE, '..')
const SRC = path.join(PKG, 'src')
/**
 * Output root. `PRISM_TOKENS_DIST` redirects it so the determinism gate can
 * build twice into two temporary directories and byte-compare without touching
 * the live `dist/` a dev server may be holding.
 */
const DIST = process.env.PRISM_TOKENS_DIST
  ? path.resolve(process.env.PRISM_TOKENS_DIST)
  : path.join(PKG, 'dist')
/** Generated staging area. Not committed — the descriptors are the source of truth. */
const STAGE = path.join(PKG, '.generated')

/**
 * Style Dictionary resolves `source` with globby, which requires forward slashes.
 * path.join() emits backslashes on Windows, which silently match zero files.
 */
const toGlob = (p) => p.split(path.sep).join('/')

/** UTF-8 BOMs (common from Windows editors) are not valid JSON — strip before parsing. */
async function readJson(file) {
  return JSON.parse((await readFile(file, 'utf8')).replace(/^\uFEFF/, ''))
}

/** Every file under `dir`, relative and posix-separated. Missing dir yields []. */
async function listFiles(dir) {
  const out = []
  const walk = async (current) => {
    let entries
    try {
      entries = await readdir(current, { withFileTypes: true })
    } catch {
      return
    }
    for (const entry of entries) {
      const full = path.join(current, entry.name)
      if (entry.isDirectory()) await walk(full)
      else out.push(toGlob(path.relative(dir, full)))
    }
  }
  await walk(dir)
  return out
}

const FOUNDATION = toGlob(path.join(SRC, 'foundation', '*.tokens.json'))
const RADIUS = toGlob(path.join(SRC, 'semantic', 'radius.tokens.json'))
const LIGHT = toGlob(path.join(SRC, 'semantic', 'light.tokens.json'))
const DARK = toGlob(path.join(SRC, 'semantic', 'dark.tokens.json'))
const THEMES_DIR = path.join(SRC, 'themes')

/** Only root-level tokens are semantic; foundation tokens are nested ramps. */
const isSemantic = (token) => token.path.length === 1

const BANNER = [
  '/*',
  ' * Generated by @nanisoft/prism-tokens. Do not edit by hand.',
  ' * Source: packages/tokens/src  (DTCG 2025.10)',
  ' */',
  '',
].join('\n')

// Without a name transform every leaf defaults to its last path segment, which
// collides across ramps (color.neutral.0 and spacing.0 are both "0").
StyleDictionary.registerTransform({
  name: 'ds/name-path',
  type: 'name',
  transform: (token) => token.path.join('-'),
})

StyleDictionary.registerFormat({
  name: 'ds/css-vars',
  format: ({ dictionary, options }) => {
    const selector = options.selector ?? ':root'
    const decls = dictionary.allTokens
      .filter(isSemantic)
      .map((t) => `  ${cssVarName(t.path)}: ${readToken(t)};`)
      .join('\n')
    return `${BANNER}${selector} {\n${decls}\n}\n`
  },
})

/**
 * The mode-independent groups, in one `@theme static` block.
 *
 * `@theme` tree-shakes unused variables and `@theme inline` emits only variables
 * reachable from a generated utility, so only `@theme static` guarantees every
 * declared motion, typography and layout token reaches CSS. This is what closes
 * the recorded defect where those groups were authored but unbound.
 */
function staticThemeDecls() {
  const decls = []
  const push = (name, value) => decls.push(`  ${name}: ${value};`)
  const emitGroup = (group, valueOf = readToken) => {
    for (const [key, token] of groupEntries(foundationTree, [group])) {
      push(cssVarName([group, key]), valueOf(token))
    }
  }

  emitGroup('font')
  emitGroup('font-weight')

  // `text.*` carries its line-height companion, which Tailwind reads from
  // `--text-*--line-height` rather than from `leading.*`.
  for (const [key, token] of groupEntries(foundationTree, ['text'])) {
    const name = cssVarName(['text', key])
    push(name, readToken(token))
    const lineHeight = token?.$extensions?.['com.nanisoft.prism']?.lineHeight
    if (lineHeight !== undefined) push(`${name}--line-height`, String(lineHeight))
  }

  emitGroup('leading')
  emitGroup('tracking')

  // Spacing: the base multiplier (step 1) becomes `--spacing`, which keeps
  // arbitrary multipliers resolving, then every authored step follows.
  const spacing = groupEntries(foundationTree, ['spacing'])
  const baseSpacing = spacing.find(([key]) => key === '1')
  if (baseSpacing) push('--spacing', readToken(baseSpacing[1]))
  for (const [key, token] of spacing) push(cssVarName(['spacing', key]), readToken(token))

  emitGroup('duration')
  emitGroup('ease')

  // Tailwind's `duration-*` utility reads `--transition-duration-*`, not
  // `--duration-*`, so the duration tokens are mirrored here.
  push('--transition-duration-fast', 'var(--duration-fast)')
  push('--transition-duration-base', 'var(--duration-base)')
  push('--transition-duration-slow', 'var(--duration-slow)')
  push('--default-transition-duration', 'var(--duration-base)')
  push('--default-transition-timing-function', 'var(--ease-out)')

  emitGroup('shadow')

  emitGroup('breakpoint')
  // The authored breakpoint set is exhaustive: xl and 2xl are closed so an
  // `xl:` utility cannot silently resolve to a value this repository never wrote.
  push('--breakpoint-xl', 'initial')
  push('--breakpoint-2xl', 'initial')

  emitGroup('container')
  return decls
}

StyleDictionary.registerFormat({
  name: 'ds/tailwind-theme',
  format: ({ dictionary }) => {
    const semantic = dictionary.allTokens.filter(isSemantic)

    // Colors: expose each semantic token as a Tailwind color utility.
    // `--background` -> `--color-background` -> `bg-background`
    const colorUtilities = semantic
      .filter((t) => t.path[0] !== 'radius')
      .map((t) => `  --color-${t.path.join('-')}: var(${cssVarName(t.path)});`)

    // Radius: one base token drives the whole scale.
    const radiusScale = [
      '  --radius-sm: calc(var(--radius) * 0.6);',
      '  --radius-md: calc(var(--radius) * 0.8);',
      '  --radius-lg: var(--radius);',
      '  --radius-xl: calc(var(--radius) * 1.4);',
      '  --radius-2xl: calc(var(--radius) * 1.8);',
      '  --radius-3xl: calc(var(--radius) * 2.2);',
      '  --radius-4xl: calc(var(--radius) * 2.6);',
    ]

    const inline = `@theme inline {\n${[...colorUtilities, ...radiusScale].join('\n')}\n}\n`
    const staticBlock = `@theme static {\n${staticThemeDecls().join('\n')}\n}\n`
    return `${BANNER}${inline}\n${staticBlock}`
  },
})

/** Flat, fully-resolved token map for the docs site and any JS consumer. */
StyleDictionary.registerFormat({
  name: 'ds/flat-json',
  format: ({ dictionary }) => {
    const out = {}
    for (const token of dictionary.allTokens) {
      out[token.path.join('.')] = {
        value: readToken(token),
        ...(token.$description ? { description: token.$description } : {}),
      }
    }
    return JSON.stringify(out, null, 2)
  },
})

/** JS module so the docs site can read resolved values without parsing CSS. */
StyleDictionary.registerFormat({
  name: 'ds/js-module',
  format: ({ dictionary }) => {
    const semantic = {}
    const foundation = {}
    for (const token of dictionary.allTokens) {
      const key = token.path.join('.')
      ;(isSemantic(token) ? semantic : foundation)[key] = readToken(token)
    }
    return [
      BANNER,
      `export const semantic = ${JSON.stringify(semantic, null, 2)}`,
      '',
      `export const foundation = ${JSON.stringify(foundation, null, 2)}`,
      '',
      'export default { semantic, foundation }',
      '',
    ].join('\n')
  },
})

const platform = (files, buildPath = DIST) => ({
  transforms: ['ds/name-path'],
  buildPath: `${buildPath}${path.sep}`,
  files,
})

/* ── Base (shadcn-compatible neutral) theme ────────────────────────────────── */

const baseSd = {
  light: new StyleDictionary({
    usesDtcg: true,
    source: [FOUNDATION, RADIUS, LIGHT],
    platforms: {
      css: platform([
        { destination: 'light.css', format: 'ds/css-vars', filter: isSemantic, options: { selector: ':root' } },
        { destination: 'theme.css', format: 'ds/tailwind-theme', filter: isSemantic },
        { destination: 'tokens.light.json', format: 'ds/flat-json', filter: isSemantic },
        { destination: 'tokens.foundation.json', format: 'ds/flat-json' },
        { destination: 'index.js', format: 'ds/js-module' },
      ]),
    },
  }),
  dark: new StyleDictionary({
    usesDtcg: true,
    include: [FOUNDATION, RADIUS],
    source: [DARK],
    platforms: {
      css: platform([
        { destination: 'dark.css', format: 'ds/css-vars', filter: isSemantic, options: { selector: '.dark' } },
        { destination: 'tokens.dark.json', format: 'ds/flat-json', filter: isSemantic },
      ]),
    },
  }),
}

/* ── Theme expansion ──────────────────────────────────────────────────────── */

/**
 * Expand each descriptor into a complete DTCG token file under .generated/, then
 * compile it with the same Style Dictionary path as the base theme. Stage rather
 * than hand-build CSS so reference resolution and colour handling stay in one place.
 */
async function stageThemes() {
  const ids = (await readdir(THEMES_DIR))
    .filter((f) => f.endsWith('.json'))
    .map((f) => path.basename(f, '.json'))
    .sort()

  const manifest = []

  for (const id of ids) {
    const descriptor = await readJson(path.join(THEMES_DIR, `${id}.json`))
    const expanded = expandTheme(id)

    const dir = path.join(STAGE, id)
    await mkdir(dir, { recursive: true })

    for (const mode of ['light', 'dark']) {
      await writeFile(
        path.join(dir, `${mode}.tokens.json`),
        JSON.stringify({ ...expanded[mode], radius: { $value: descriptor.radius } }, null, 2),
        'utf8',
      )
    }

    manifest.push({
      id,
      name: descriptor.name,
      description: descriptor.$description,
      radius: `${descriptor.radius.value}${descriptor.radius.unit}`,
    })
  }

  return { ids, manifest }
}

const { ids: themeIds, manifest } = await stageThemes()

/**
 * Themes are selectable at runtime, so each emits scoped selectors rather than
 * overwriting :root. Per-theme light/dark files are also written for consumers who
 * only ever want one theme and want a plain :root block to copy.
 *
 * The selector is the `themeSelector` output switch. The build ships the
 * attribute-agnostic shape so a `data-pack` attribute on any element re-points
 * the custom properties for its subtree.
 */
const themeSd = Object.fromEntries(
  themeIds.map((id) => [
    id,
    {
      light: new StyleDictionary({
        usesDtcg: true,
        source: [FOUNDATION, toGlob(path.join(STAGE, id, 'light.tokens.json'))],
        platforms: {
          css: platform([
            { destination: `themes/${id}/light.css`, format: 'ds/css-vars', filter: isSemantic, options: { selector: themeSelector(id, 'light', THEME_SELECTOR_STYLE) } },
            { destination: `themes/${id}/root.css`, format: 'ds/css-vars', filter: isSemantic, options: { selector: ':root' } },
            { destination: `themes/${id}/tokens.light.json`, format: 'ds/flat-json', filter: isSemantic },
          ]),
        },
      }),
      dark: new StyleDictionary({
        usesDtcg: true,
        include: [FOUNDATION],
        source: [toGlob(path.join(STAGE, id, 'dark.tokens.json'))],
        platforms: {
          css: platform([
            { destination: `themes/${id}/dark.css`, format: 'ds/css-vars', filter: isSemantic, options: { selector: themeSelector(id, 'dark', THEME_SELECTOR_STYLE) } },
            { destination: `themes/${id}/tokens.dark.json`, format: 'ds/flat-json', filter: isSemantic },
          ]),
        },
      }),
    },
  ]),
)

/* ── Run ──────────────────────────────────────────────────────────────────── */

/**
 * Do not wipe dist/ up front. The docs app imports these files by path, and a
 * dev server holding a module graph will re-resolve them mid-session; an `rm -rf`
 * leaves a window where the target does not exist, which poisons the bundler's
 * resolver for the rest of the session. Instead, write over the top and prune
 * afterwards, so dist/ is never absent.
 */
const existing = await listFiles(DIST)
await mkdir(DIST, { recursive: true })

await baseSd.light.buildAllPlatforms()
await baseSd.dark.buildAllPlatforms()
for (const id of themeIds) {
  await themeSd[id].light.buildAllPlatforms()
  await themeSd[id].dark.buildAllPlatforms()
}

await writeFile(
  path.join(DIST, 'themes.json'),
  `${JSON.stringify(manifest, null, 2)}\n`,
  'utf8',
)

/**
 * Emit a single static module with every theme's resolved tokens, in both modes.
 *
 * The docs site imports this rather than reading dist/ with fs at request time:
 * a runtime `createRequire(...).resolve()` does not survive the server bundler, and
 * static imports stay analysable. Adding a theme needs no change on the consumer.
 *
 * Both modes are emitted because a consumer that paints a literal swatch has to
 * know which mode it is painting for. The theme switcher reads a theme's `primary`
 * and hands it to a dot as an inline style, and an inline style has no cascade to
 * fall back on: with only the light values published, switching to dark left the
 * five pastel dots holding their light colours while the unstyled `default` dot
 * correctly re-resolved to the dark step, so the one swatch that tracked the mode
 * was the one with no literal on it. Emitting only light was the bug; the
 * per-theme `tokens.dark.json` this reads already existed.
 */
{
  const lightTokens = {}
  const darkTokens = {}
  for (const id of themeIds) {
    lightTokens[id] = JSON.parse(
      await readFile(path.join(DIST, `themes/${id}/tokens.light.json`), 'utf8'),
    )
    darkTokens[id] = JSON.parse(
      await readFile(path.join(DIST, `themes/${id}/tokens.dark.json`), 'utf8'),
    )
  }
  await writeFile(
    path.join(DIST, 'themes', 'index.js'),
    [
      BANNER,
      `export const themeTokens = ${JSON.stringify(lightTokens, null, 2)}`,
      '',
      `export const themeTokensDark = ${JSON.stringify(darkTokens, null, 2)}`,
      '',
      'export default themeTokens',
      '',
    ].join('\n'),
    'utf8',
  )
}

/* ── DTCG projection ──────────────────────────────────────────────────────── */

const dtcgFiles = await writeDtcg({ distDir: DIST, srcDir: SRC, foundationTree, manifest })

/* ── Verify ───────────────────────────────────────────────────────────────── */

// Guard: a build that silently emits `undefined` is worse than a failed build.
const emitted = [
  'light.css',
  'dark.css',
  'theme.css',
  'index.js',
  'tokens.light.json',
  'tokens.dark.json',
  'tokens.foundation.json',
  'themes.json',
  'themes/index.js',
  ...themeIds.flatMap((id) => [
    `themes/${id}/light.css`,
    `themes/${id}/dark.css`,
    `themes/${id}/root.css`,
    `themes/${id}/tokens.light.json`,
    `themes/${id}/tokens.dark.json`,
  ]),
  ...dtcgFiles,
]
for (const file of emitted) {
  const contents = await readFile(path.join(DIST, file), 'utf8')
  if (contents.includes(': undefined') || contents.includes(':undefined')) {
    throw new Error(`${file} contains an undefined token value — check the source tokens.`)
  }
}

// Guard: every theme must expose the same token set, or components break silently
// when a consumer switches theme.
const reference = Object.keys(JSON.parse(await readFile(path.join(DIST, 'tokens.light.json'), 'utf8')))
for (const id of themeIds) {
  const keys = Object.keys(
    JSON.parse(await readFile(path.join(DIST, `themes/${id}/tokens.light.json`), 'utf8')),
  )
  const missing = reference.filter((k) => !keys.includes(k))
  if (missing.length) {
    throw new Error(`theme "${id}" is missing ${missing.length} token(s): ${missing.join(', ')}`)
  }
}

// The emitted-contract check (`pnpm check`, scripts/check-emitted-contract.mjs) is
// what asserts the bound groups reached CSS and equal the authored values. It
// reads the DTCG source and this output, so it runs after the build rather than
// inside it.

/* ── Prune ────────────────────────────────────────────────────────────────── */

// Only after every check passes, so a failed run leaves the last good output in
// place rather than taking a running dev server's imports away.
/**
 * Anything that existed before this build and is not a current output is stale —
 * a removed theme, or output from an older version of this script.
 *
 * Diffing against the declared output list, not against a directory scan taken
 * after the build: stale files are still on disk at that point, so a scan would
 * list them as "produced" and nothing would ever be pruned.
 */
const emittedSet = new Set(emitted.map(toGlob))
const stale = existing.filter((file) => !emittedSet.has(file))
for (const file of stale) {
  await rm(path.join(DIST, file), { force: true })
}

// Removing a theme leaves its directory behind; drop any that is now empty.
for (const id of await readdir(path.join(DIST, 'themes'), { withFileTypes: true })) {
  if (id.isDirectory() && !emittedSet.has(`themes/${id.name}/light.css`)) {
    await rm(path.join(DIST, 'themes', id.name), { recursive: true, force: true })
  }
}

console.log(`tokens: built ${reference.length} semantic tokens -> dist/`)
console.log(`  base theme      light.css  dark.css  theme.css  index.js`)
console.log(`  ${themeIds.length} themes        ${themeIds.join(', ')}`)
console.log(`  manifests       tokens.{light,dark,foundation}.json  themes.json`)
console.log(`  dtcg            foundation + semantic + ${themeIds.length * 2} pack files + manifest`)
if (stale.length) {
  console.log(`  pruned          ${stale.length} stale file(s)`)
}
