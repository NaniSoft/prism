/**
 * Pre-bakes antd's theme variables for all four pack × mode combinations
 * (ticket 02's flash-free dark-mode recipe).
 *
 * With `cssVar: { key: 'prism-<pack>-<mode>' }` + `hashed: false`, theme
 * identity collapses into one ruleset per key: `.{key} { --prism-*: … }` plus
 * the component-level variable rulesets `.{key}.ant-*-css-var { --prism-*: … }`.
 * Component *styles* are theme-agnostic (they reference `var(--prism-*)`), so
 * the four variable sets are all the site needs pre-baked: the blocking
 * bootstrap script swaps the `.{key}` class on <html> and the whole page
 * re-themes without a flash. Emits `app/antd-vars.css`.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

process.env.NODE_ENV = 'production'; // antd's dev-only deprecation warnings would otherwise pollute the build

import React from 'react';
import { extractStyle } from '@ant-design/static-style-extract';
import { getPrismTheme, prismBrandPacks } from '@nanisoft/prism-tokens';
import { PrismProvider } from '@nanisoft/prism-ui/provider';

// Derived from the registered packs — a new pack in prism-tokens pre-bakes its
// variable rulesets with no edit here.
const PACKS = Object.keys(prismBrandPacks);
const MODES = ['light', 'dark'];
const OUT_FILE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'app', 'antd-vars.css');

/**
 * Keep only the rules scoped to `key`'s variable class (the bare token
 * ruleset and the component-level `.{key}.ant-*-css-var` rulesets). The
 * theme-agnostic component styles that make up the rest of the extraction are
 * baked into every page by AntdRegistry at prerender — duplicating them four
 * times here would quadruple the payload for nothing.
 */
export function keepThemeVariableRules(css, key) {
  const keep = (selector) => selector === `.${key}` || selector.startsWith(`.${key}.`);
  const walk = (text) => {
    const out = [];
    let i = 0;
    while (i < text.length) {
      const brace = text.indexOf('{', i);
      if (brace === -1) break;
      const selector = text.slice(i, brace).trim();
      let depth = 1;
      let j = brace + 1;
      while (j < text.length && depth > 0) {
        const ch = text[j];
        if (ch === '{') depth += 1;
        else if (ch === '}') depth -= 1;
        j += 1;
      }
      const body = text.slice(brace + 1, j - 1);
      if (selector.startsWith('@') && depth === 0) {
        const inner = walk(body);
        if (inner) out.push(`${selector}{${inner}}`);
      } else if (keep(selector)) {
        out.push(`${selector}{${body}}`);
      }
      i = j;
    }
    return out.join('');
  };
  return walk(css);
}

function bakeTheme(pack, mode) {
  const theme = getPrismTheme(pack, mode);
  const full = extractStyle({
    customTheme: (node) => React.createElement(PrismProvider, { prismTheme: theme }, node),
  });
  const rules = keepThemeVariableRules(full, theme.cssVarKey);
  if (!rules.includes('--prism-color-primary')) {
    throw new Error(`bake-antd-css: no theme variables extracted for ${pack}/${mode}`);
  }
  return { theme, rules };
}

const HEADER = `/*
 * GENERATED by apps/site/scripts/bake-antd-css.mjs — do not edit.
 * One pre-baked antd variable ruleset per pack × mode, keyed by the
 * \`prism-<pack>-<mode>\` cssVar class (ticket 02's class-swap recipe).
 */
`;

const chunks = [HEADER];
for (const pack of PACKS) {
  for (const mode of MODES) {
    const { theme, rules } = bakeTheme(pack, mode);
    chunks.push(`/* ${theme.pack} · ${theme.mode} (${theme.cssVarKey}) */\n${rules}\n`);
    console.log(`bake-antd-css: ${theme.cssVarKey} → ${rules.length} bytes`);
  }
}

const css = chunks.join('\n');
const totalBytes = Buffer.byteLength(css, 'utf8');

// Byte-budget guard (audit 2026-09-25): the single pre-baked file keeps the
// class-swap flash-free for every stored theme and covers every component the
// docs demo. Splitting per theme would trade that guarantee away for stored
// non-default themes, so growth is capped here instead of silently drifting.
const MAX_TOTAL_BYTES = 640 * 1024;
if (totalBytes > MAX_TOTAL_BYTES) {
  throw new Error(
    `bake-antd-css: ${totalBytes} bytes exceeds the ${MAX_TOTAL_BYTES}-byte budget — trim the bake or ship per-theme chunks with a synchronous loader`,
  );
}

await mkdir(path.dirname(OUT_FILE), { recursive: true });
await writeFile(OUT_FILE, css);
console.log(
  `bake-antd-css: wrote ${path.relative(process.cwd(), OUT_FILE)} (${(totalBytes / 1024).toFixed(0)} KB of ${MAX_TOTAL_BYTES / 1024} KB budget)`,
);
