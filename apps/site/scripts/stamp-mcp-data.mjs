/**
 * Stamps the Worker with the corpus build date (ticket 22, review round 1).
 *
 * The Worker bundles `@nanisoft/prism-llms`' `data.json` at build time, so the
 * corpus build date is knowable in-scope: this script reads that file's mtime
 * — its last real build — and emits `worker/generated/mcp-data-built.ts`,
 * which `worker/mcp.ts` passes to `createPrismMcpServer(store, { built })` for
 * the ADR-0004 §2 `list_items` header.
 *
 * Runs before every build and deploy (see package.json scripts); the generated
 * module is gitignored, this script is the committed source of truth.
 *
 * Honesty rule: a missing corpus is a broken build (the bundle needs it anyway)
 * and throws with a pointer to the prism-llms build, same convention as
 * copy-llms.mjs; an unreadable mtime emits `undefined`, and the MCP header
 * omits the `(built …)` clause rather than fabricating a date.
 */
import { mkdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO_ROOT = path.resolve(SITE_ROOT, '..', '..');
const DATA_JSON = path.join(REPO_ROOT, 'packages', 'llms', 'dist', 'data.json');
const OUT = path.join(SITE_ROOT, 'worker', 'generated', 'mcp-data-built.ts');

let stats;
try {
  stats = await stat(DATA_JSON);
} catch {
  throw new Error(
    `stamp-mcp-data: ${DATA_JSON} not found — the Worker bundles it, so the prism-llms build must run first (pnpm build).`,
  );
}

const mtime = stats.mtime;
const built = Number.isNaN(mtime.getTime()) ? undefined : mtime.toISOString().slice(0, 10);

await mkdir(path.dirname(OUT), { recursive: true });
await writeFile(
  OUT,
  [
    '// Generated by scripts/stamp-mcp-data.mjs — do not edit.',
    '// The corpus build date (UTC) printed by the MCP `list_items` header (ADR-0004 §2).',
    `export const PRISM_DOCS_BUILT: string | undefined = ${JSON.stringify(built)};`,
    '',
  ].join('\n'),
);

console.log(`stamp-mcp-data: corpus built ${built ?? '<unknown — header will omit the built clause>'} → ${path.relative(SITE_ROOT, OUT)}`);
