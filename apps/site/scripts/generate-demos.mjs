/**
 * Builds the item manifest: the demo registry and the tree the routing tree is
 * built from.
 *
 * Two artefacts, one walk, one rule. The walk is `item-content.mjs`, which says
 * where an Item's documentation and its Demo are, so this script holds no path
 * of its own and cannot disagree with the corpus builder or the gate about what
 * exists.
 *
 *   `src/generated/demos.ts`   the live preview, the copy control and the
 *                              corpus, keyed by slug, carrying each Demo's
 *                              verbatim source and a measured client flag;
 *   `src/generated/item-groups.json`  which folder each Item's documentation
 *                              is filed under, which is the only thing the
 *                              routing tree reads to know where an Item sits.
 *
 * The client flag is measured the same way `analyze-blocks.mjs` measures a
 * block: a `'use client'` directive, one of the client hooks, or a `next/*`
 * client import. It is reported by the page rather than guessed.
 *
 * The import specifiers are relative to the generated file, not aliased, because
 * a Demo now lives outside `src`: one rule that covers the flat demo root and
 * an Item's own folder, and no second list to keep in step.
 *
 * Run: node scripts/generate-demos.mjs
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { readItemContent } from './item-content.mjs'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const SITE = path.join(HERE, '..')
const ITEMS = path.join(SITE, 'items')
const DEMOS = path.join(SITE, 'src', 'demos')
const OUT_DIR = path.join(SITE, 'src', 'generated')
const OUT = path.join(OUT_DIR, 'demos.ts')
const OUT_GROUPS = path.join(OUT_DIR, 'item-groups.json')

const USE_CLIENT = /^[ \t]*['"]use client['"]/m
const CLIENT_HOOKS = /\buse(State|Effect|Memo|Ref|Reducer|Callback|Context|LayoutEffect)\s*\(/
const NEXT_CLIENT_IMPORT =
  /\bimport\s+[^\n;]*\bfrom\s+['"]next\/(navigation|router|image|head)\b/

function isClient(source) {
  return USE_CLIENT.test(source) || CLIENT_HOOKS.test(source) || NEXT_CLIENT_IMPORT.test(source)
}

function exportName(slug) {
  return `${slug
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')}Demo`
}

/** The specifier the generated registry imports one Demo by, from itself. */
function specifierFor(demo) {
  const relative = path.relative(OUT_DIR, demo).split(path.sep).join('/').replace(/\.tsx$/, '')
  return relative.startsWith('.') ? relative : `./${relative}`
}

const items = await readItemContent(ITEMS, DEMOS)

const entries = []
for (const item of items) {
  if (item.demo === null) {
    console.error(
      `demos: ${item.slug} has no Demo: ${item.beside ? 'no file beside its documentation' : 'no file in the demo root'}`,
    )
    process.exit(1)
  }
  const source = await readFile(item.demo, 'utf8')
  entries.push({ slug: item.slug, source, client: isClient(source), specifier: specifierFor(item.demo) })
}

const imports = entries
  .map(({ slug, specifier }) => `import ${exportName(slug)} from '${specifier}'`)
  .join('\n')

const registry = entries
  .map(
    ({ slug, source, client }) =>
      `  ${JSON.stringify(slug)}: {\n` +
      `    component: ${exportName(slug)},\n` +
      `    client: ${client},\n` +
      `    source: ${JSON.stringify(source)},\n` +
      `  },`,
  )
  .join('\n')

const output = `// Generated by scripts/generate-demos.mjs. Do not edit.
// Source: every Item's Demo, beside its documentation
import type { ComponentType } from 'react'

${imports}

export type DemoEntry = {
  component: ComponentType
  /** True when the demo itself crosses a client boundary. */
  client: boolean
  /** The demo file, verbatim. The copy control shows exactly this. */
  source: string
}

export const demos: Record<string, DemoEntry> = {
${registry}
}

/** Every slug the registry knows, for the coverage check. */
export const demoSlugs = ${JSON.stringify(entries.map((entry) => entry.slug))} as const

export type DemoSlug = (typeof demoSlugs)[number]
`

/**
 * The manifest, one entry per Item, in the same order as the registry.
 *
 * Every Item appears, including the ones with an empty group, so a missing entry
 * is a stale manifest rather than an Item that quietly reads as unfiled. The
 * routing tree checks both directions and refuses to build on a disagreement.
 */
const groups = Object.fromEntries(items.map((item) => [item.slug, item.group]))

await mkdir(OUT_DIR, { recursive: true })
await writeFile(OUT, output, 'utf8')
await writeFile(OUT_GROUPS, `${JSON.stringify(groups, null, 2)}\n`, 'utf8')

const clientCount = entries.filter((entry) => entry.client).length
const nested = items.filter((item) => item.group.length > 0)
console.log(
  `demos: ${entries.length} registered, ${entries.length - clientCount} server / ${clientCount} ` +
    `client, ${nested.length} filed under a folder -> ${path.relative(SITE, OUT)}`,
)
