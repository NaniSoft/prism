/**
 * Builds the demo registry from `src/demos/*.tsx`.
 *
 * One self-contained `.tsx` per demo is the single source for three consumers:
 * the live preview, the copy control and the corpus. This script scans the
 * directory and emits a typed registry keyed by catalogue slug, carrying the
 * component, its verbatim source and a measured client flag.
 *
 * The client flag is measured the same way `analyze-blocks.mjs` measures a
 * block: a `'use client'` directive, one of the client hooks, or a `next/*`
 * client import. It is reported by the page rather than guessed.
 *
 * Run: node scripts/generate-demos.mjs
 */
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const SITE = path.join(HERE, '..')
const DEMOS = path.join(SITE, 'src', 'demos')
const OUT_DIR = path.join(SITE, 'src', 'generated')
const OUT = path.join(OUT_DIR, 'demos.ts')

const USE_CLIENT = /^[ \t]*['"]use client['"]/m
const CLIENT_HOOKS = /\buse(State|Effect|Memo|Ref|Reducer|Callback|Context|LayoutEffect)\s*\(/
const NEXT_CLIENT_IMPORT =
  /\bimport\s+[^\n;]*\bfrom\s+['"]next\/(navigation|router|image|head)\b/

function isClient(source) {
  return USE_CLIENT.test(source) || CLIENT_HOOKS.test(source) || NEXT_CLIENT_IMPORT.test(source)
}

function exportName(slug) {
  return `${slug
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')}Demo`
}

const files = (await readdir(DEMOS).catch(() => []))
  .filter((name) => name.endsWith('.tsx'))
  .sort()

const entries = []
for (const file of files) {
  const slug = file.replace(/\.tsx$/, '')
  const source = await readFile(path.join(DEMOS, file), 'utf8')
  entries.push({ slug, source, client: isClient(source) })
}

const imports = entries
  .map(({ slug }) => `import ${exportName(slug)} from '@/demos/${slug}'`)
  .join('\n')

const registry = entries
  .map(
    ({ slug, source, client }) =>
      `  ${JSON.stringify(slug)}: {\n` +
      `    component: ${exportName(slug)},\n` +
      `    client: ${client},\n` +
      `    source: ${JSON.stringify(source)},\n` +
      `  },`,
  )
  .join('\n')

const output = `// Generated by scripts/generate-demos.mjs. Do not edit.
// Source: apps/site/src/demos/*.tsx
import type { ComponentType } from 'react'

${imports}

export type DemoEntry = {
  component: ComponentType
  /** True when the demo itself crosses a client boundary. */
  client: boolean
  /** The demo file, verbatim. The copy control shows exactly this. */
  source: string
}

export const demos: Record<string, DemoEntry> = {
${registry}
}

/** Every slug the registry knows, for the coverage check. */
export const demoSlugs = ${JSON.stringify(entries.map((entry) => entry.slug))} as const

export type DemoSlug = (typeof demoSlugs)[number]
`

await mkdir(OUT_DIR, { recursive: true })
await writeFile(OUT, output, 'utf8')

const clientCount = entries.filter((entry) => entry.client).length
console.log(
  `demos: ${entries.length} registered, ${entries.length - clientCount} server / ${clientCount} client -> ${path.relative(SITE, OUT)}`,
)
