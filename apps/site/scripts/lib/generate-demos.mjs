/**
 * The demos registry generator (ticket 12's app-level Demo wire, source side).
 *
 * Walks `content/<section>/<item>/demos/*.tsx` and emits a TypeScript module
 * mapping `<section>/<item>/<slug>` to both the live component (an import of
 * the demo file) and its verbatim source (embedded at codegen time). The
 * example id is the filename slug — the same file prism-llms serves as
 * `get_item_source` and the MDX fence.
 */
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';

export const SECTIONS = ['docs', 'components', 'blocks', 'pages', 'blog'];

/** Walk the content tree; returns `{ id, importPath, code }` per demo, sorted. */
export async function collectDemos(contentRoot, generatedDir) {
  const entries = [];
  for (const section of SECTIONS) {
    const sectionDir = path.join(contentRoot, section);
    if (!existsSync(sectionDir)) continue;
    for (const item of (await readdir(sectionDir)).sort()) {
      const demosDir = path.join(sectionDir, item, 'demos');
      if (!existsSync(demosDir)) continue;
      for (const file of (await readdir(demosDir)).sort()) {
        if (!file.endsWith('.tsx')) continue;
        const slug = file.replace(/\.tsx$/, '');
        const code = (await readFile(path.join(demosDir, file), 'utf8')).replace(/\r\n/g, '\n');
        const absolute = path.join(demosDir, file);
        entries.push({
          id: `${section}/${item}/${slug}`,
          importPath: path.relative(generatedDir, absolute).replace(/\\/g, '/').replace(/\.tsx$/, ''),
          code,
        });
      }
    }
  }
  return entries.sort((a, b) => a.id.localeCompare(b.id));
}

/** Render the registry module. Extensionless relative import (bundler resolution). */
export function renderDemosModule(entries) {
  const imports = entries.map((entry, index) => `import Demo${index} from '${entry.importPath}';`);
  const record = entries.map(
    (entry, index) => `  ${JSON.stringify(entry.id)}: { Component: Demo${index}, code: ${JSON.stringify(entry.code)} },`,
  );
  return `// GENERATED by apps/site/scripts/generate.mjs — do not edit.
// One entry per co-located demo (ticket 12's self-contained contract): the
// live component and its verbatim source both come from the same file.
import type { ComponentType } from 'react';

${imports.join('\n')}

export interface DemoEntry {
  Component: ComponentType;
  /** The demo file's source, verbatim. */
  code: string;
}

export const demos: Record<string, DemoEntry> = {
${record.join('\n')}
};
`;
}

/** Generate `app/generated`-style registry module content for the site. */
export async function generateDemosRegistry(contentRoot, outFile) {
  const entries = await collectDemos(contentRoot, path.dirname(outFile));
  await mkdir(path.dirname(outFile), { recursive: true });
  await writeFile(outFile, renderDemosModule(entries));
  return entries.length;
}
